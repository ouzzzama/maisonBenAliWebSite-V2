  /* -------------------------------------------------------------- car tabs */
  function wireRentCar(root) {
    var card = root.querySelector(".bp-card--rentcar");
    if (!card) return;

    var tabs = card.querySelectorAll(".bp-rent-tab");
    var media = card.querySelectorAll(".bp-rent-media img");
    var name = card.querySelector("[data-car-name]");
    var meta = card.querySelector("[data-car-meta]");
    var price = card.querySelector("[data-car-price]");
    var cta = card.querySelector('[data-bp-book="car"]');

    function select(id) {
      var car = CARS[0];
      CARS.forEach(function (item) { if (item.id === id) car = item; });

      Array.prototype.forEach.call(tabs, function (tab) {
        var active = tab.getAttribute("data-car") === car.id;
        tab.classList.toggle("is-active", active);
        tab.setAttribute("aria-selected", String(active));
        tab.tabIndex = active ? 0 : -1;
      });

      Array.prototype.forEach.call(media, function (img) {
        img.classList.toggle("is-active", img.getAttribute("data-car") === car.id);
      });

      name.textContent = car.name;
      meta.textContent = carMeta(car);
      price.textContent = money(car.price);
      cta.setAttribute("data-bp-id", car.id);
    }

    Array.prototype.forEach.call(tabs, function (tab) {
      tab.tabIndex = tab.classList.contains("is-active") ? 0 : -1;
      tab.addEventListener("click", function () {
        select(tab.getAttribute("data-car"));
      });
      tab.addEventListener("keydown", function (event) {
        if (event.key !== "ArrowRight" && event.key !== "ArrowLeft") return;
        event.preventDefault();
        var list = Array.prototype.slice.call(tabs);
        var index = list.indexOf(tab);
        var next = (index + (event.key === "ArrowRight" ? 1 : -1) + list.length) % list.length;
        list[next].focus();
        select(list[next].getAttribute("data-car"));
      });
    });
  }

  /* ------------------------------------------------------- lead gallery */
  function wireLeadGallery(root) {
    var lead = root.querySelector("#bpLeadCard");
    if (!lead) return;

    var imgs = lead.querySelectorAll(".bp-lead-media img");
    var dots = lead.querySelectorAll(".bp-lead-dot");
    var caption = lead.querySelector("[data-lead-caption]");
    var index = 0;
    var timer = null;
    var reduced = window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches;

    if (imgs.length < 2) return;

    function show(target) {
      index = (target + imgs.length) % imgs.length;
      Array.prototype.forEach.call(imgs, function (img, i) {
        img.classList.toggle("is-active", i === index);
      });
      Array.prototype.forEach.call(dots, function (dot, i) {
        dot.classList.toggle("is-active", i === index);
        dot.setAttribute("aria-current", String(i === index));
      });
      if (caption) caption.textContent = LEAD_LABELS[index % LEAD_LABELS.length];
    }

    function stop() {
      if (timer) {
        clearInterval(timer);
        timer = null;
      }
    }

    function start() {
      if (reduced || timer) return;
      timer = setInterval(function () { show(index + 1); }, 7000);
    }

    function step(delta) {
      show(index + delta);
      stop();
      start();
    }

    Array.prototype.forEach.call(dots, function (dot) {
      dot.addEventListener("click", function () {
        show(parseInt(dot.getAttribute("data-lead-slide"), 10) || 0);
        stop();
        start();
      });
    });

    lead.addEventListener("keydown", function (event) {
      if (event.key === "ArrowRight") {
        event.preventDefault();
        step(1);
      } else if (event.key === "ArrowLeft") {
        event.preventDefault();
        step(-1);
      }
    });

    lead.addEventListener("mouseenter", stop);
    lead.addEventListener("mouseleave", start);
    lead.addEventListener("focusin", stop);
    lead.addEventListener("focusout", start);

    var touchX = null;
    lead.addEventListener("touchstart", function (event) {
      touchX = event.changedTouches[0].clientX;
    }, { passive: true });
    lead.addEventListener("touchend", function (event) {
      if (touchX === null) return;
      var delta = event.changedTouches[0].clientX - touchX;
      touchX = null;
      if (Math.abs(delta) > 45) step(delta < 0 ? 1 : -1);
    }, { passive: true });

    start();
  }

  /* ------------------------------------------------------------------ build */
  function build(page) {
    if (!page || page.querySelector(".bp-bento-sec")) return;

    var legacy = document.querySelector(".renvia-project-details-sec");
    var ctx = legacy ? legacyContext(legacy) : { title: "Résidence d'appartements", location: "Agadir, Maroc", hero: "assets/images/innerpage/project/p1-hero.jpg", specs: [] };

    if (!ctx.hero) ctx.hero = "assets/images/innerpage/project/p1-hero.jpg";

    /* the bento replaces the old presentation blocks, nothing else */
    Array.prototype.forEach.call(
      page.querySelectorAll(".bp-hero-sec, .bp-values-sec, .bp-plans-sec"),
      function (block) { block.parentNode.removeChild(block); }
    );

    var section = document.createElement("section");
    section.className = "bp-bento-sec";
    section.innerHTML =
      '<div class="container">' +
        '<div class="bp-bento-grid">' +
          leadCard(ctx) +
          productInfoCard(ctx) +
          specsBar(ctx) +
          stayCard(STAYS[0]) +
          legendCard() +
          rentCarCard() +
          serviceTiles().join("") +
          contactTiles().join("") +
        "</div>" +
      "</div>";

    page.insertBefore(section, page.firstChild);

    wireLeadGallery(section);
    wireRentCar(section);
    wireDrawer();

    drawer.dataset.projectTitle = ctx.title;
    drawer.dataset.projectImage = ctx.hero;

    section.addEventListener("click", function (event) {
      var trigger = event.target.closest ? event.target.closest("[data-bp-book]") : null;
      if (!trigger) return;
      event.preventDefault();
      openDrawer(trigger.getAttribute("data-bp-book"), trigger.getAttribute("data-bp-id"));
    });

    if (window.ScrollTrigger && window.ScrollTrigger.refresh) {
      window.ScrollTrigger.refresh();
    }
  }

  function boot() {
    var page = document.querySelector(".bp-page");
    if (page) {
      build(page);
      return;
    }
    /* project-bento.js builds .bp-page on DOMContentLoaded; if it runs later
       than us, wait for it rather than silently doing nothing. */
    var tries = 0;
    var timer = setInterval(function () {
      tries += 1;
      var built = document.querySelector(".bp-page");
      if (built) {
        clearInterval(timer);
        build(built);
      } else if (tries > 40) {
        clearInterval(timer);
      }
    }, 50);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", boot);
  } else {
    boot();
  }
